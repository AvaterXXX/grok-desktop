  function bucketsOf(map) {
    const buckets = new Map();
    for (const key of Object.keys(map)) {
      const ch = key.charAt(0);
      if (!buckets.has(ch)) buckets.set(ch, []);
      buckets.get(ch).push(key);
    }
    for (const list of buckets.values()) {
      list.sort((a, b) => b.length - a.length);
    }
    return { map, buckets };
  }

  const stages = [
    [bucketsOf(ST_PHRASES), bucketsOf(ST_CHARS)],
    [bucketsOf(TW_PHRASES), bucketsOf(TW_VARIANT_PHRASES), bucketsOf(TW_VARIANTS)],
  ];

  function convertWith(stage, text) {
    let out = "";
    let i = 0;
    while (i < text.length) {
      let matched = false;
      const ch = text.charAt(i);
      for (const table of stage) {
        const list = table.buckets.get(ch);
        if (!list) continue;
        for (const key of list) {
          if (text.startsWith(key, i)) {
            out += table.map[key];
            i += key.length;
            matched = true;
            break;
          }
        }
        if (matched) break;
      }
      if (!matched) {
        out += ch;
        i += 1;
      }
    }
    return out;
  }

